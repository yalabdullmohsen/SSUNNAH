#!/usr/bin/env python3
"""يولّد PrayerWidget/SunnahLocalDataWidgets.swift: أربعة ودجتات من بيانات التطبيق المحلية حرفيًا (بلا نص شرعي مكتوب باليد).
الاستعمال: python3 scripts/gen-local-data-widgets.py   (من جذر المستودع)"""
import json, re, pathlib
R = pathlib.Path(__file__).resolve().parent.parent
D = R / "ios-native/Data"
OUT = R / "artifacts/majalis/ios/App/PrayerWidget/SunnahLocalDataWidgets.swift"

def q(s): return json.dumps(s, ensure_ascii=False)

def fadail(ids):
    m = {i["id"]: i for i in json.load(open(D / "fiqh/fadail-aamal.json"))}
    out = []
    for k in ids:
        i = m[k]; body, _, src = i["body"].partition("\n\nالمصدر:")
        out.append((body.strip(), (src.strip() or i["sources"][0]["ref"])))
    return out

adhkar = [(i["text"].strip(), (i.get("source_name") or i.get("reference") or "").strip())
          for i in json.load(open(D / "adhkar/verified-adhkar.json")) if i["category_id"] == "adh-after-salah"]
adhkar = [(t, s) for t, s in adhkar if t and s]
asma = json.load(open(D / "aqidah/asma-husna.json")); asma = asma if isinstance(asma, list) else list(asma.values())[0]
asma = [(f'{a["arabic"]} — {a["meaning"]}'.strip(), (a.get("reference") or "").strip()) for a in asma if a.get("documentation_status") == "sourced" and a.get("reference")]
duha = fadail(["fadail-f32"])
friday = fadail(["fadail-f99", "fadail-f104", "fadail-f63"])

def pool(name, items):
    rows = ",\n".join(f"        .init(text: {q(t)}, source: {q(s)})" for t, s in items)
    return f"    static let {name}: [WidgetLocalContent.Item] = [\n{rows}\n    ]\n"

src = f'''// GENERATED by scripts/gen-local-data-widgets.py — لا تعدّل يدويًا. المحتوى حرفيًا من ios-native/Data (حقل المصدر مرفق بكل عنصر).
import WidgetKit
import SwiftUI

enum LocalDataWidgetPools {{
{pool("duha", duha)}{pool("afterSalah", adhkar)}{pool("asma", asma)}{pool("fridayFasting", friday)}}}

enum LocalDataWidgetKind: CaseIterable {{
    case duha, afterSalah, asma, fridayFasting

    var kind: String {{
        switch self {{
        case .duha: return SunnahWidgetKind.localDuha
        case .afterSalah: return SunnahWidgetKind.localAfterSalah
        case .asma: return SunnahWidgetKind.localAsma
        case .fridayFasting: return SunnahWidgetKind.localFridayFasting
        }}
    }}
    var title: String {{
        switch self {{
        case .duha: return "الضحى"
        case .afterSalah: return "أذكار بعد الصلاة"
        case .asma: return "الأسماء الحسنى"
        case .fridayFasting: return "الجمعة والصيام"
        }}
    }}
    var symbol: String {{
        switch self {{
        case .duha: return "sun.max"
        case .afterSalah: return "hands.sparkles"
        case .asma: return "sparkles"
        case .fridayFasting: return "moon.stars"
        }}
    }}
    var pool: [WidgetLocalContent.Item] {{
        switch self {{
        case .duha: return LocalDataWidgetPools.duha
        case .afterSalah: return LocalDataWidgetPools.afterSalah
        case .asma: return LocalDataWidgetPools.asma
        case .fridayFasting: return LocalDataWidgetPools.fridayFasting
        }}
    }}
    /// أذكار الصلاة تتبدّل كل ساعة؛ البقية يوميًا.
    var hourly: Bool {{ self == .afterSalah }}

    func pick(at date: Date, timeZone: TimeZone) -> WidgetLocalContent.Item? {{
        guard !pool.isEmpty else {{ return nil }}
        let unit: Double = hourly ? 3600 : 86400
        let n = Int(floor((date.timeIntervalSince1970 + Double(timeZone.secondsFromGMT(for: date))) / unit))
        return pool[((n % pool.count) + pool.count) % pool.count]
    }}
}}

struct LocalDataWidgetView: View {{
    @SunnahFamily private var family
    let spec: LocalDataWidgetKind
    let entry: CatalogWidgetEntry

    private var sizes: [CGFloat] {{
        switch family {{
        case .systemLarge, .systemExtraLarge: return [26, 23, 20, 18, 16, 14, 12]
        case .systemMedium: return [22, 20, 18, 16, 14, 12]
        case .accessoryRectangular: return [14, 13, 12, 11]
        default: return [20, 18, 16, 14, 12]
        }}
    }}

    var body: some View {{
        let item = spec.pick(at: entry.date, timeZone: HourlyAdhkarProvider.timeZone(for: entry))
        VStack(spacing: 6) {{
            Text(spec.title)
                .font(WidgetType.secondary(12))
                .foregroundStyle(SunnahBrandColors.gold)
                .widgetAccentable()
            Spacer(minLength: 0)
            if let item {{
                ViewThatFits(in: .vertical) {{
                    ForEach(sizes, id: \\.self) {{ size in
                        Text(item.text)
                            .font(.system(size: size, weight: .semibold, design: .serif))
                            .foregroundStyle(family == .accessoryRectangular ? Color.primary : SunnahWidgetTheme.primaryText)
                            .multilineTextAlignment(.center)
                            .fixedSize(horizontal: false, vertical: true)
                            .frame(maxWidth: .infinity)
                    }}
                }}
                Spacer(minLength: 0)
                if family != .accessoryRectangular, !item.source.isEmpty {{
                    Text(item.source)
                        .font(WidgetType.secondary(11))
                        .foregroundStyle(SunnahWidgetTheme.secondaryText)
                        .lineLimit(2)
                        .minimumScaleFactor(0.7)
                }}
            }} else {{
                SunnahCalmCard(symbol: spec.symbol, phrase: "المحتوى قيد التوثيق")
            }}
        }}
        .frame(maxWidth: .infinity)
        .sunnahCardLayout(family == .accessoryRectangular ? 0 : 12)
        .modifier(LocalDataWidgetSurface())
        .accessibilityElement(children: .combine)
    }}
}}

private struct LocalDataWidgetSurface: ViewModifier {{
    func body(content: Content) -> some View {{
        if #available(iOSApplicationExtension 17.0, *) {{
            content.modifier(SunnahAccessoryInset()).containerBackground(for: .widget) {{ SunnahWidgetTheme.homeGradientDeep }}
        }} else {{
            content.modifier(SunnahAccessoryInset()).background(SunnahWidgetTheme.homeGradientDeep)
        }}
    }}
}}

private struct LocalDataWidgetBody: View {{
    let spec: LocalDataWidgetKind
    let entry: CatalogWidgetEntry
    var body: some View {{
        LocalDataWidgetView(spec: spec, entry: entry).environment(\\.layoutDirection, .rightToLeft)
    }}
}}

struct LocalDuhaWidget: Widget {{
    var body: some WidgetConfiguration {{
        StaticConfiguration(kind: LocalDataWidgetKind.duha.kind, provider: HourlyAdhkarProvider()) {{ LocalDataWidgetBody(spec: .duha, entry: $0) }}
            .configurationDisplayName("الضحى").description("فضل صلاة الضحى من بيانات التطبيق مع مصدره.")
            .supportedFamilies(SunnahWidgetFamilySupport.quran)
    }}
}}
struct LocalAfterSalahWidget: Widget {{
    var body: some WidgetConfiguration {{
        StaticConfiguration(kind: LocalDataWidgetKind.afterSalah.kind, provider: HourlyAdhkarProvider()) {{ LocalDataWidgetBody(spec: .afterSalah, entry: $0) }}
            .configurationDisplayName("أذكار بعد الصلاة").description("ذكر من أذكار ما بعد الصلاة يتجدد كل ساعة مع مصدره.")
            .supportedFamilies(SunnahWidgetFamilySupport.quran)
    }}
}}
struct LocalAsmaWidget: Widget {{
    var body: some WidgetConfiguration {{
        StaticConfiguration(kind: LocalDataWidgetKind.asma.kind, provider: HourlyAdhkarProvider()) {{ LocalDataWidgetBody(spec: .asma, entry: $0) }}
            .configurationDisplayName("الأسماء الحسنى").description("اسم من الأسماء الحسنى بمعناه ومرجعه، يتجدد يوميًا.")
            .supportedFamilies(SunnahWidgetFamilySupport.quran)
    }}
}}
struct LocalFridayFastingWidget: Widget {{
    var body: some WidgetConfiguration {{
        StaticConfiguration(kind: LocalDataWidgetKind.fridayFasting.kind, provider: HourlyAdhkarProvider()) {{ LocalDataWidgetBody(spec: .fridayFasting, entry: $0) }}
            .configurationDisplayName("الجمعة والصيام").description("من فضائل الجمعة والصيام في بيانات التطبيق مع مصدرها.")
            .supportedFamilies(SunnahWidgetFamilySupport.quran)
    }}
}}

'''
OUT.write_text(src)
print(len(duha), len(adhkar), len(asma), len(friday))
