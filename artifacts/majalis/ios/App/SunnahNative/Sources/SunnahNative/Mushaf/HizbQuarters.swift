    public static var quarterCount: Int { starts.count }
    public static var hizbCount: Int { starts.count / 4 }

    /// رقم الربع (1...240) الذي تقع فيه الآية.
    public static func quarter(surah: Int, ayah: Int) -> Int {
        var lo = 0, hi = starts.count
        while lo < hi {
            let mid = (lo + hi) / 2
            let s = starts[mid]
            if (s.surah, s.ayah) <= (surah, ayah) { lo = mid + 1 } else { hi = mid }
        }
        return max(lo, 1)
    }

    /// رقم الحزب (1...60) للآية.
    public static func hizb(surah: Int, ayah: Int) -> Int { (quarter(surah: surah, ayah: ayah) - 1) / 4 + 1 }

    /// الحزب لمعرّف آية بصيغة «س:ع».
    public static func hizb(ayahID: String) -> Int? {
        let p = ayahID.split(separator: ":").compactMap { Int($0) }
        return p.count == 2 ? hizb(surah: p[0], ayah: p[1]) : nil
    }

    /// تسمية الموضع كما في المصحف المطبوع أسفل الصفحة: «الحزب ٣» / «ربع الحزب ٣» / «نصف الحزب ٣» / «ثلاثة أرباع الحزب ٣».
    public static func label(ayahID: String) -> String? {
        let p = ayahID.split(separator: ":").compactMap { Int($0) }
        guard p.count == 2 else { return nil }
        let q = quarter(surah: p[0], ayah: p[1])
        let h = ArabicNumerals.string((q - 1) / 4 + 1)
        switch (q - 1) % 4 {
        case 1: return "ربع الحزب \(h)"
        case 2: return "نصف الحزب \(h)"
        case 3: return "ثلاثة أرباع الحزب \(h)"
        default: return "الحزب \(h)"
        }
    }
